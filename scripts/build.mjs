/**
 * The Qeetrix token build.
 *
 * One source — DTCG 2025.10 under src/tokens/, composed by src/qeetrix.resolver.json — read and
 * validated by Terrazzo (scripts/lib/load.mjs), then written as one output per kind of consumer:
 *
 *   dist/tokens.css              every web app. :root holds every public token for the default
 *                                modes; one block per modifier context ([data-qx-color-scheme],
 *                                [data-qx-density]) re-declares exactly the tokens that context
 *                                changes. Values are fully resolved, so a nested scope is always
 *                                correct, and primitives are never published.
 *   dist/dtcg/                   the standard source and resolver, as published, plus one resolved
 *                                document per colour scheme — for iOS, Android, Figma, docs sites.
 *   dist/index.js + index.d.ts   the values JavaScript reads as numbers or strings, with exact
 *                                literal types; brandTheme() comes from src/brand.ts via tsc.
 *
 * Run: bun run build
 */
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { cssVariable, declarationsFor } from "./lib/css.mjs";
import {
  EXTENSION,
  isPublic,
  loadResolver,
  platformsOf,
  RESOLVER,
  resolverDocument,
  SRC,
  sortedIds,
} from "./lib/load.mjs";

const OUT = fileURLToPath(new URL("../dist/", import.meta.url));
rmSync(OUT, { recursive: true, force: true });
mkdirSync(`${OUT}dtcg`, { recursive: true });

const resolver = await loadResolver();
const modifiers = Object.entries(resolverDocument().modifiers);
const defaults = resolver.inputDefault;
const base = resolver.apply(defaults);

const onWeb = (id, token) => {
  const platforms = platformsOf(token);
  return isPublic(id) && (platforms === undefined || platforms.includes("web"));
};
const kebab = (s) => s.replace(/[A-Z]/g, (ch) => `-${ch.toLowerCase()}`);
const block = (selector, lines) => `${selector} {\n${lines.map((l) => `  ${l}`).join("\n")}\n}\n`;
const declare = (set, ids) =>
  ids.flatMap((id) => declarationsFor(set[id], set)).map(([name, value]) => `${name}: ${value};`);

// ---- fonts ---------------------------------------------------------------------
// The two typefaces the tokens name, with their SIL Open Font Licences: Qeet Sans is Cal Sans
// (github.com/calcom/sans; wght 400–700, opsz 8–45, GEOM 0–100) and Fira Code (wght 300–700).
// The web gets subsets, cut by scripts/subset-fonts.py and listed in src/fonts/subsets.json: per
// face a latin, a latin-ext and an "other" file, each declared with the unicode-range of exactly
// the characters it holds, so a page downloads only what its text uses and no character pulls in
// a whole font (QTRX-10). Qeet Sans is cut upright and italic, YTAS and SHRP pinned. The full
// variable files ship too, for other platforms. The @font-face rules open tokens.css, so the one
// import brings the fonts. The GEOM letter style is set per role by components (each role's
// --qx-typography-*-font-geometry), not here: Safari ignores the font-variation-settings descriptor.
cpSync(fileURLToPath(new URL("fonts/", SRC)), `${OUT}fonts`, { recursive: true });
const subsets = JSON.parse(readFileSync(new URL("fonts/subsets.json", SRC), "utf8"));
const fontFaces = subsets
  .flatMap(({ family, weight, style, files }) =>
    files.map(
      ({ file, unicodeRange }) =>
        `@font-face {\n  font-family: "${family}";\n  src: url("./fonts/${file}") format("woff2");\n  font-weight: ${weight};\n  font-style: ${style};\n  font-display: swap;\n  unicode-range: ${unicodeRange};\n}`,
    ),
  )
  .join("\n");

// ---- dist/tokens.css --------------------------------------------------------

// Breakpoints are published as @custom-media, not variables: var() cannot be used in a media query.
const publicIds = sortedIds(base).filter(
  (id) => onWeb(id, base[id]) && !id.startsWith("breakpoint."),
);
const colorSchemeFor = (input) => input.colorScheme;

const sections = [
  [
    "/**",
    " * Qeetrix design tokens — GENERATED by @qeetrix/tokens (scripts/build.mjs). Do not edit by hand:",
    " * edit src/tokens/** in qeetrix-tokens and run `bun run build`.",
    " *",
    " * :root holds the default modes. Set data-qx-color-scheme and data-qx-density on any element to",
    " * switch a subtree. The fonts (Qeet Sans, Fira Code; SIL Open Font Licence 1.1, dist/fonts/) load",
    " * only when text uses them.",
    " */",
  ].join("\n"),
  fontFaces,
  block(":root", [`color-scheme: ${colorSchemeFor(defaults)};`, ...declare(base, publicIds)]),
];

// One block per modifier context, holding exactly the tokens that modifier changes. The resolver's
// modifiers are orthogonal (tests/source.test.ts), so no two blocks ever declare the same token.
for (const [name, modifier] of modifiers) {
  const contexts = Object.keys(modifier.contexts).map((context) => [
    context,
    resolver.apply({ ...defaults, [name]: context }),
  ]);
  const varying = publicIds.filter(
    (id) =>
      new Set(contexts.map(([, set]) => JSON.stringify(declarationsFor(set[id], set)))).size > 1,
  );
  for (const [context, set] of contexts) {
    const extra = name === "colorScheme" ? [`color-scheme: ${context};`] : [];
    sections.push(
      block(`[data-qx-${kebab(name)}="${context}"]`, [...extra, ...declare(set, varying)]),
    );
  }
}

// Reduced motion: every duration collapses. Durations never vary by mode, so :root covers every scope.
const durations = publicIds.filter((id) => base[id].$type === "duration");
sections.push(
  [
    "@media (prefers-reduced-motion: reduce) {",
    "  :root {",
    ...durations.map((id) => `    ${cssVariable(id)}: 0ms;`),
    "  }",
    "}",
    "",
  ].join("\n"),
);

writeFileSync(`${OUT}tokens.css`, `${sections.join("\n\n").replace(/\n{3,}/g, "\n\n")}`);

// ---- dist/custom-media.css -------------------------------------------------------
// The breakpoints, as @custom-media, in their own opt-in sheet: browsers don't read @custom-media
// yet, so only an app whose CSS build transpiles them imports it (Lightning CSS with
// drafts.customMedia, postcss-custom-media). tokens.css stays plain CSS every pipeline accepts.
writeFileSync(
  `${OUT}custom-media.css`,
  [
    "/**",
    " * Qeetrix breakpoints — GENERATED by @qeetrix/tokens (scripts/build.mjs). The window size classes",
    " * as @custom-media, for a CSS build that transpiles them: @media (--qx-viewport-expanded) { … }.",
    " */",
    ...sortedIds(base)
      .filter((id) => id.startsWith("breakpoint."))
      .sort((a, b) => base[a].$value.value - base[b].$value.value)
      .map(
        (id) =>
          `@custom-media --qx-viewport-${id.slice("breakpoint.".length)} (width >= ${base[id].$value.value}${base[id].$value.unit});`,
      ),
    "",
  ].join("\n"),
);

// ---- dist/dtcg/ ---------------------------------------------------------------
// The source and resolver as authored — the standard way to express every mode — plus one resolved
// document per colour scheme (default density) for tools that do not run a resolver yet. A token
// that is a pure reference stays one, so tools keep the primitive → semantic relationships.

cpSync(fileURLToPath(new URL("tokens/", SRC)), `${OUT}dtcg/tokens`, { recursive: true });
cpSync(fileURLToPath(RESOLVER), `${OUT}dtcg/qeetrix.resolver.json`);

const [, colorScheme] = modifiers.find(([name]) => name === "colorScheme");
for (const context of Object.keys(colorScheme.contexts)) {
  const set = resolver.apply({ ...defaults, colorScheme: context });
  const doc = {
    $description: `Qeetrix design tokens — the ${context} colour scheme at default density, resolved. Generated by @qeetrix/tokens from qeetrix.resolver.json; do not edit.`,
    $extensions: { [EXTENSION]: { input: { ...defaults, colorScheme: context } } },
  };
  for (const id of sortedIds(set)) {
    const token = set[id];
    const entry = {
      $type: token.$type,
      $value: token.aliasOf && set[token.aliasOf] ? `{${token.aliasOf}}` : token.$value,
    };
    if (token.$description) entry.$description = token.$description;
    if (token.$deprecated) entry.$deprecated = token.$deprecated;
    if (token.$extensions && Object.keys(token.$extensions).length > 0) {
      entry.$extensions = token.$extensions;
    }
    const path = id.split(".");
    let node = doc;
    for (const segment of path.slice(0, -1)) node = node[segment] ??= {};
    node[path.at(-1)] = entry;
  }
  writeFileSync(`${OUT}dtcg/${context}.tokens.json`, `${JSON.stringify(doc, null, 2)}\n`);
}

// ---- dist/index.js + dist/index.d.ts ------------------------------------------
// The values JavaScript has to read as numbers or strings. Module and declarations are written from
// one structure, so they cannot disagree.

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, ch) => ch.toUpperCase());
/** Tokens under `prefix`, as a nested object keyed by camelCase path segments. */
function pick(prefix, map) {
  const out = {};
  for (const id of sortedIds(base).filter((i) => i.startsWith(`${prefix}.`))) {
    const path = id
      .slice(prefix.length + 1)
      .split(".")
      .map(camel);
    let node = out;
    for (const segment of path.slice(0, -1)) node = node[segment] ??= {};
    node[path.at(-1)] = map(base[id]);
  }
  return out;
}
const cssValue = (token) => declarationsFor(token, base)[0][1];
const inPx = (token) => {
  if (token.$value.unit !== "px") throw new Error(`${token.id} must be in px for JavaScript`);
  return token.$value.value;
};
const inMs = (token) =>
  token.$value.unit === "s" ? token.$value.value * 1000 : token.$value.value;

const VALUES = [
  ["DURATION", "Motion durations, in milliseconds.", pick("motion.duration", inMs)],
  ["EASING", "Motion easing curves, as CSS timing functions.", pick("motion.easing", cssValue)],
  [
    "SPRING",
    "Springs for native-style motion (stiffness, damping ratio; mass 1).",
    pick("motion.spring", (t) => t.$value),
  ],
  ["ICON_SIZE", "Icon box sizes, in pixels.", pick("size.icon", inPx)],
  ["ICON_STROKE", "Icon stroke widths.", pick("icon.stroke", (t) => t.$value)],
  ["BREAKPOINT", "Window size class thresholds, in pixels.", pick("breakpoint", inPx)],
  ["COMPONENT", "Component geometry, as CSS lengths.", pick("component", cssValue)],
];

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;
const property = (key) => (IDENTIFIER.test(key) ? key : JSON.stringify(key));
function literal(value, depth, asType) {
  if (value === null || typeof value !== "object") return JSON.stringify(value);
  const pad = "  ".repeat(depth + 1);
  const lines = Object.entries(value).map(([key, v]) =>
    asType
      ? `${pad}readonly ${property(key)}: ${literal(v, depth + 1, true)};`
      : `${pad}${property(key)}: ${literal(v, depth + 1, false)},`,
  );
  return `{\n${lines.join("\n")}\n${"  ".repeat(depth)}}`;
}
const banner = [
  "/**",
  " * Qeetrix typed token values — GENERATED by @qeetrix/tokens (scripts/build.mjs). Do not edit by",
  " * hand: edit src/tokens/** and run `bun run build`. Everything else is a --qx-* CSS variable.",
  " */",
].join("\n");
const render = (asType) =>
  [
    banner,
    "",
    ...VALUES.map(
      ([name, doc, value]) =>
        `/** ${doc} */\nexport ${asType ? "declare const" : "const"} ${name}${asType ? ": " : " = "}${literal(value, 0, asType)};\n`,
    ),
    asType
      ? 'export { brandTheme, TENANT_TOKENS } from "./brand.js";\nexport type { BrandTheme, TenantToken } from "./brand.js";\n'
      : 'export { brandTheme, TENANT_TOKENS } from "./brand.js";\n',
  ].join("\n");
writeFileSync(`${OUT}index.js`, render(false));
writeFileSync(`${OUT}index.d.ts`, render(true));

console.log(
  `✔ Qeetrix tokens built — ${publicIds.length} public tokens → dist/tokens.css, dist/dtcg/, dist/index.{js,d.ts}, dist/fonts/`,
);
